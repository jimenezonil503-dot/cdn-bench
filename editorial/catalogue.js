export const pair = (zh,en) => ({zh,en});
export function chapter(zhHeading,enHeading,zh,en,extra={}) {
 const z=zh.trim().split(/\n\s*\n/),e=en.trim().split(/\n\s*\n/);
 if(z.length!==e.length)throw new Error('Paragraph translation mismatch: '+zhHeading);
 return {heading:pair(zhHeading,enHeading),paragraphs:z.map((p,i)=>pair(p,e[i])),bullets:[],...extra};
}
